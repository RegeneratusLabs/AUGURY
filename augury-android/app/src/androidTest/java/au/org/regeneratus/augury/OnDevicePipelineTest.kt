/**
 * ============================================================================
 *  THE ON-DEVICE PIPELINE — the half no host can run
 * ============================================================================
 *
 * `VisionParityTest` proves the Kotlin maths against Python using a *recorded* CLS
 * token; it cannot load ONNX Runtime Mobile, cannot decode a JPEG, and cannot run
 * the 688 MB GGUF. This test is the complement: it drives the real
 * [AuguryGatewayImpl] on a device with the artifacts the app downloaded and
 * verified, and answers the two questions the handover left open:
 *
 *  1. **Does the photo path work at all?** `OnnxEncoder` had never loaded the
 *     346 MB graph on a device. Every sample here is a gallery photo whose row is
 *     *in the shipped index* (chosen by `tools/select_device_vision_samples.py`
 *     from the row-aligned `keys.json` / `files.json`), so its reference embedding
 *     is in `embeddings.npy`: a device result that disagrees is a device bug, not
 *     a hard query.
 *  2. **Does bounding the decode change the answer?** `DecodeBounds` is a
 *     device-heap bound and must not move the identification. That is measured
 *     here against the real graph, with the full-resolution decode as the control.
 *
 * The floors are deliberately far below the recorded 85.9% top-1: they catch a
 * *broken* pipeline (which produces an exception, an empty list, or near-random
 * species), not a model accuracy argument. The measured numbers are logged under
 * the `AuguryDeviceTest` tag and are what goes into
 * `docs/vision-kotlin-verification.md`.
 *
 * Run:
 *   ./gradlew :app:connectedDebugAndroidTest
 * or, without Gradle:
 *   adb shell am instrument -w au.org.regeneratus.augury.test/androidx.test.runner.AndroidJUnitRunner
 */
@RunWith(AndroidJUnit4::class)
class OnDevicePipelineTest {

    private companion object {
        const val TAG = "AuguryDeviceTest"

        /** Of 12 samples: the recorded model does ~86% top-1 and ~95% top-3. */
        const val MIN_TOP1 = 8
        const val MIN_TOP3 = 10

        /** formatter, facts, vision-index, encoder. */
        const val EXPECTED_ARTIFACTS = 4

        /** The product requires three distinct candidates, always. */
        const val REQUIRED_CANDIDATES = 3
    }

    private class Sample(val file: String, val species: String)

    private val instrumentation get() = InstrumentationRegistry.getInstrumentation()

    /** The app under test: its `filesDir` holds the downloaded artifacts. */
    private val context get() = instrumentation.targetContext

    /** The test APK's own assets, generated by the sample selector. */
    private val testAssets get() = instrumentation.context.assets

    private fun samples(): List<Sample> {
        val text = testAssets.open("vision-samples/samples.json")
            .bufferedReader(Charsets.UTF_8).use { it.readText() }
        val rows = JSONArray(text)
        return (0 until rows.length()).map {
            val row = rows.getJSONObject(it)
            Sample(row.getString("file"), row.getString("species"))
        }
    }

    private fun sampleBytes(file: String): ByteArray =
        testAssets.open("vision-samples/$file").use { it.readBytes() }

    /** The real gateway, with the manifest loaded. */
    private suspend fun loadedGateway(): AuguryGatewayImpl {
        val gateway = AuguryGatewayImpl.create(context)
        assertNotNull("AuguryGatewayImpl.create() returned null — no writable storage?", gateway)
        assertNotNull("the manifest did not load — is the device online?", gateway!!.loadManifest())
        return gateway
    }

    // ── 1. the state this test depends on ───────────────────────────────────

    @Test
    fun everyArtifactIsInstalledAndReady() = runBlocking {
        val state = loadedGateway().artifactState()
        assertEquals("unexpected artifact count", EXPECTED_ARTIFACTS, state.artifacts.size)
        val notReady = state.artifacts.filter { !it.isReady }
        assertTrue(
            "artifacts not ready: ${notReady.map { "${it.name}=${it.status}" }}",
            notReady.isEmpty(),
        )
    }

    // ── 2. the photo path, end to end ───────────────────────────────────────

    @Test
    fun thePhotoPathIdentifiesGalleryPhotos() = runBlocking {
        val gateway = loadedGateway()
        val samples = samples()
        assertTrue("no samples bundled; run tools/select_device_vision_samples.py", samples.isNotEmpty())

        val before = Debug.getPss()
        var top1 = 0
        var top3 = 0
        var named = 0

        for (sample in samples) {
            val outcome = gateway.identify(sampleBytes(sample.file), "Australia")
            assertNull("${sample.file}: photo path unavailable", outcome.unavailableReason)

            val candidates = outcome.candidates
            assertEquals(
                "${sample.file}: expected $REQUIRED_CANDIDATES candidates",
                REQUIRED_CANDIDATES, candidates.size,
            )
            assertEquals(
                "${sample.file}: candidates must be distinct species",
                REQUIRED_CANDIDATES, candidates.map { it.key }.distinct().size,
            )
            for (i in 1 until candidates.size) {
                assertTrue(
                    "${sample.file}: scores must descend, got ${candidates.map { it.score }}",
                    candidates[i - 1].score >= candidates[i].score,
                )
            }

            val keys = candidates.map { it.key }
            val hit1 = keys.first() == sample.species
            val hit3 = keys.contains(sample.species)
            if (hit1) top1++
            if (hit3) top3++
            if (!candidates[0].commonName.isNullOrBlank()) named++
            Log.i(
                TAG,
                "photo ${sample.file}: top1=${keys[0]} %.4f truth=%s %s | shown as '%s' | top3=%s".format(
                    candidates[0].score, sample.species,
                    if (hit1) "HIT" else if (hit3) "top3" else "MISS",
                    candidates[0].displayName,
                    keys,
                ),
            )
        }

        val after = Debug.getPss()
        Log.i(
            TAG,
            "photo path: top1=$top1/${samples.size} top3=$top3/${samples.size} " +
                "named=$named/${samples.size} pss ${before}kB -> ${after}kB",
        )
        assertTrue("top-1 $top1/${samples.size} is below the floor $MIN_TOP1", top1 >= MIN_TOP1)
        assertTrue("top-3 $top3/${samples.size} is below the floor $MIN_TOP3", top3 >= MIN_TOP3)
        // The confirm card's headline comes from the species database, not from the
        // index key. 170 of the index's 173 species carry a common name, so a low
        // count here means the display lookup regressed, not that the data lacks one.
        assertTrue(
            "only $named/${samples.size} top-1 candidates carried a display name",
            named >= samples.size - 2,
        )
    }

    // ── 3. the decode bound must not move the answer ────────────────────────

    @Test
    fun theDecodeBoundDoesNotChangeTheAnswer() = runBlocking {
        val gateway = loadedGateway()
        val pipeline = gateway.visionPipelineForTest()
        assertNotNull("the vision pipeline would not build from the installed artifacts", pipeline)
        val live = pipeline!!

        // Make the bound bite deterministically: upscale the sample to twice the
        // target, re-encode it losslessly, then compare the full-resolution decode
        // of those bytes with the subsampled one. Same source pixels for both, so
        // the only variable is `inSampleSize`.
        val source = sampleBytes(samples().first().file)
        val header = BitmapFactory.Options().apply { inJustDecodeBounds = true }
        BitmapFactory.decodeByteArray(source, 0, source.size, header)
        val longest = max(header.outWidth, header.outHeight)
        val target = 2 * DecodeBounds.TARGET_LONGEST_EDGE
        val width = max(1, header.outWidth * target / longest)
        val height = max(1, header.outHeight * target / longest)

        val scaled = Bitmap.createScaledBitmap(
            BitmapFactory.decodeByteArray(source, 0, source.size), width, height, true,
        )
        val sampleSize = DecodeBounds.sampleSizeFor(scaled.width, scaled.height)
        val png = ByteArrayOutputStream().also { scaled.compress(Bitmap.CompressFormat.PNG, 100, it) }
        Log.i(
            TAG,
            "decode parity: source ${header.outWidth}x${header.outHeight} -> " +
                "${scaled.width}x${scaled.height}, comparing sampleSize 1 vs $sampleSize",
        )
        scaled.recycle()
        val bytes = png.toByteArray()

        val full = live.identify(decodeRgb(bytes, sampleSize = 1))
        val bounded = live.identify(decodeRgb(bytes, sampleSize = sampleSize))

        Log.i(
            TAG,
            "decode parity: full=${full.top1.key}@${full.top1.score} " +
                "bounded=${bounded.top1.key}@${bounded.top1.score}",
        )
        assertEquals("the decode bound changed the top-1", full.top1.key, bounded.top1.key)
        assertEquals(
            "the decode bound changed the whole ranking",
            full.candidates.map { it.key }, bounded.candidates.map { it.key },
        )
        assertTrue(
            "the top-1 score moved by ${abs(full.top1.score - bounded.top1.score)}",
            abs(full.top1.score - bounded.top1.score) < 0.02f,
        )
    }

    // ── 4. the formatter, and the constraint it is subject to ───────────────

    @Test
    fun theFormatterGeneratesAGroundedStoryAndReleasesTheEncoder() = runBlocking {
        val gateway = loadedGateway()
        // Warm the photo path first, so this measures the transition the product
        // actually makes: photo -> story.
        assertNotNull(gateway.visionPipelineForTest())
        val withEncoder = Debug.getPss()

        val result = gateway.story(
            speciesKey = "taraxacum officinale",
            question = "What does dandelion indicate about my soil?",
            region = "Australia",
        )
        assertNotNull("story() returned null for dandelion in Australia", result)
        val story = result!!

        assertTrue("the story is blank", story.story.isNotBlank())
        assertTrue("no indicator rows were resolved", story.reading.indicators.isNotEmpty())
        // If the GGUF could not be loaded this is false and the deterministic
        // template stands in. Proving it is true is the point of this test.
        assertTrue(
            "the formatter model did not produce the draft (usedModel=false): the app fell back " +
                "to the template",
            story.usedModel,
        )

        val afterStory = Debug.getPss()
        Log.i(
            TAG,
            "story: usedModel=${story.usedModel} repairs=${story.repairs.size} " +
                "chars=${story.story.length} pss ${withEncoder}kB -> ${afterStory}kB",
        )
        for (repair in story.repairs) Log.i(TAG, "grounding repair: $repair")

        // Hard constraint 7: the encoder was released so the GGUF could load, and
        // the next photo must rebuild it lazily.
        assertNotNull(
            "the photo path did not recover after the formatter released the encoder",
            gateway.visionPipelineForTest(),
        )
    }

    private fun decodeRgb(bytes: ByteArray, sampleSize: Int): RgbImage {
        val options = BitmapFactory.Options().apply { inSampleSize = sampleSize }
        val bitmap = BitmapFactory.decodeByteArray(bytes, 0, bytes.size, options)
            ?: error("could not decode the sample at sampleSize=$sampleSize")
        val pixels = IntArray(bitmap.width * bitmap.height)
        bitmap.getPixels(pixels, 0, bitmap.width, 0, 0, bitmap.width, bitmap.height)
        val image = RgbImage.fromArgb(pixels, bitmap.width, bitmap.height)
        bitmap.recycle()
        return image
    }
}
